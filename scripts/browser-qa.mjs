import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page = await browser.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const results=[];
try {
 await page.goto('http://127.0.0.1:3000/',{waitUntil:'networkidle'});
 await page.evaluate(async()=>{await Promise.all([...document.images].map(img=>{img.loading='eager';return img.decode().catch(()=>{});}));});
 for(const width of [320,375,390,430,768,1024,1280,1440,1920]){
  await page.setViewportSize({width,height:1000});
  const layout=await page.evaluate(()=>({viewport:innerWidth,pageWidth:document.documentElement.scrollWidth,h1:document.querySelectorAll('h1').length,missingImages:[...document.images].filter(i=>!i.complete||i.naturalWidth===0).map(i=>i.src),clipped:[...document.querySelectorAll('h1,h2,h3')].filter(el=>el.scrollWidth>el.clientWidth+2).map(el=>el.textContent)}));
  if(layout.pageWidth>width||layout.h1!==1||layout.missingImages.length||layout.clipped.length)throw new Error(`${width}px layout failed: ${JSON.stringify(layout)}`);
  results.push({width,...layout});
 }
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:'Поиск',exact:true}).click();
 await page.getByRole('searchbox').fill('красным луком');
 await expect(page.locator('.search-results>a')).toHaveCount(1);
 await expect(page.locator('.search-results>a')).toHaveAttribute('href','#black-seed-shampoo');
 await page.keyboard.press('Escape');
 await expect(page.locator('.panel:not(.product-dialog)')).not.toBeVisible();
 await page.locator('.filter-tabs').getByRole('button',{name:/Для волос/}).click();
 await expect(page.locator('.product-card')).toHaveCount(4);
 await page.locator('#ashwagandha-shampoo .product-details').click();
 await expect(page.locator('.product-dialog')).toBeVisible();
 await expect(page.locator('#product-dialog-title')).toContainText('ашваганда');
 await expect(page.locator('.product-dialog img')).toHaveAttribute('src',/ashwagandha/);
 await page.keyboard.press('Escape');
 await expect(page.locator('.product-dialog')).not.toBeVisible();
 await expect(page.locator('#ashwagandha-shampoo .product-details')).toBeFocused();
 await page.locator('.filter-tabs').getByRole('button',{name:/Дезодоранты/}).click();
 await expect(page.locator('.product-card')).toHaveCount(6);
 await page.locator('.filter-tabs').getByRole('button',{name:'Все',exact:true}).click();
 await expect(page.locator('.product-card')).toHaveCount(4);
 await page.getByRole('button',{name:/Вся подборка/}).click();
 await expect(page.locator('.product-card')).toHaveCount(11);
 await page.evaluate(async()=>{await Promise.all([...document.querySelectorAll('.product-card img')].map(img=>{img.loading='eager';return img.decode();}));});
 if(await page.locator('.product-card img').evaluateAll(imgs=>imgs.some(img=>!img.complete||img.naturalWidth===0)))throw new Error('An expanded product photo failed to load');
 await page.locator('.filter-tabs').getByRole('button',{name:'Все',exact:true}).click();
 await page.locator('#email').fill('invalid');
 await page.getByRole('button',{name:'Подписаться',exact:true}).click();
 await expect(page.locator('#subscription-feedback')).toContainText('корректный');
 await page.locator('#email').fill('example@example.com');
 await page.getByRole('button',{name:'Подписаться',exact:true}).click();
 await expect(page.locator('#subscription-feedback')).toContainText('не сохранён');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Меню',exact:true}).click();
 const focusIsInside=await page.locator('.menu-panel').evaluate(el=>el.contains(document.activeElement));
 if(!focusIsInside)throw new Error('Mobile menu failed to receive focus');
 await page.keyboard.press('Escape');
 await expect(page.getByRole('button',{name:'Меню',exact:true})).toBeFocused();
 await page.getByRole('button',{name:'Меню',exact:true}).click();
 await page.getByRole('navigation',{name:'Мобильная навигация'}).getByRole('link',{name:'Коллекции'}).click();
 await expect(page.locator('.panel:not(.product-dialog)')).not.toBeVisible();
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.evaluate(()=>scrollTo(0,0));
 mkdirSync('qa',{recursive:true});
 await page.screenshot({path:'qa/mobile-390.png',fullPage:true});
 await page.screenshot({path:'qa/mobile-top.png'});
 await page.setViewportSize({width:1440,height:1000});await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:'qa/desktop-1440.png',fullPage:true});
 await page.screenshot({path:'qa/desktop-top.png'});
 if(errors.length)throw new Error(`Browser exceptions: ${errors.join('; ')}`);
 writeFileSync('qa/results.json',JSON.stringify({layouts:results,interactions:'search, filters, newsletter validation, honest submission, mobile menu, Escape and focus restoration passed',browserErrors:errors},null,2));
 console.log('PASS: nine responsive widths, image loading, headings, search, filters, newsletter validation, menu, Escape, focus restoration; no browser exceptions.');
} finally {await browser.close();}
